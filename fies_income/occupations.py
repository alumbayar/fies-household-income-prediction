# Ordinal rank used as a proxy for earning potential; higher is more skilled.
ISCO_SKILL_LEVEL = {
    "1 - Managers": 9,
    "2 - Professionals": 8,
    "3 - Technicians and Associate Professionals": 7,
    "4 - Clerical Support Workers": 6,
    "5 - Service and Sales Workers": 5,
    "6 - Skilled Agricultural, Forestry and Fishery Workers": 4,
    "7 - Craft and Related Trades Workers": 3,
    "8 - Plant and Machine Operators, and Assemblers": 2,
    "9 - Elementary Occupations": 1,
    "0 - Armed Forces Occupations": 0,
    "Unidentifiable / Not Classifiable": -1,
    UNEMPLOYED: -1,
}


_JOB_TO_GROUP = {job: group for group, jobs in ISCO_MAPPING.items() for job in jobs}


def map_isco(occupation: pd.Series) -> tuple[pd.Series, pd.Series]:
    """Map occupation titles to their ISCO major group and skill level.

    Titles not found in ``ISCO_MAPPING`` (including missing values and
    placeholders for households without a working head) are treated as
    unemployed.

    Args:
        occupation: Household head occupation titles.

    Returns:
        A tuple of ``(group, skill)`` where ``group`` holds the ISCO major
        group label and ``skill`` holds the integer skill level.
    """
    group = occupation.map(_JOB_TO_GROUP).fillna(UNEMPLOYED)
    skill = group.map(ISCO_SKILL_LEVEL).fillna(-1).astype(int)
    return group, skill
